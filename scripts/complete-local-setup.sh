#!/usr/bin/env bash
# Interactive Aurafit setup (Azure storage + OpenAI + Crawl4AI stack)
# Run from repo root: ./scripts/complete-local-setup.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

echo "=== Aurafit setup wizard ==="
echo ""
echo "This will open Azure Portal pages. Paste the values when prompted."
echo "Already configured values in .env.local will be kept if you press Enter."
echo ""

# Load existing values as defaults
if [[ -f .env.local ]]; then
  set -a
  # shellcheck disable=SC1091
  source .env.local
  set +a
fi

open "https://portal.azure.com/#create/Microsoft.StorageAccount" 2>/dev/null || true
echo "1) Azure Storage Account → Access keys"
read -r -p "   AZURE_STORAGE_ACCOUNT_NAME [${AZURE_STORAGE_ACCOUNT_NAME:-}]: " _sa
AZURE_STORAGE_ACCOUNT_NAME="${_sa:-${AZURE_STORAGE_ACCOUNT_NAME:-}}"
read -r -p "   AZURE_STORAGE_ACCOUNT_KEY: " _sak
AZURE_STORAGE_ACCOUNT_KEY="${_sak:-${AZURE_STORAGE_ACCOUNT_KEY:-}}"
read -r -p "   AZURE_STORAGE_CONNECTION_STRING: " _scs
AZURE_STORAGE_CONNECTION_STRING="${_scs:-${AZURE_STORAGE_CONNECTION_STRING:-}}"

echo ""
open "https://oai.azure.com/portal" 2>/dev/null || true
echo "2) Azure OpenAI → Keys and Endpoint + deploy gpt-4o, text-embedding-3-large, dall-e-3"
read -r -p "   AZURE_OPENAI_ENDPOINT [${AZURE_OPENAI_ENDPOINT:-}]: " _ep
AZURE_OPENAI_ENDPOINT="${_ep:-${AZURE_OPENAI_ENDPOINT:-}}"
read -r -s -p "   AZURE_OPENAI_API_KEY: " _key
echo ""
AZURE_OPENAI_API_KEY="${_key:-${AZURE_OPENAI_API_KEY:-}}"

echo ""
echo "3) Clerk (already set unless you want to change)"
read -r -p "   NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY [${NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY:-}]: " _cpk
NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY="${_cpk:-${NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY:-}}"
read -r -s -p "   CLERK_SECRET_KEY: " _csk
echo ""
CLERK_SECRET_KEY="${_csk:-${CLERK_SECRET_KEY:-}}"

LAN_IP="$(ipconfig getifaddr en0 2>/dev/null || ipconfig getifaddr en1 2>/dev/null || echo "YOUR_LAN_IP")"

cat > .env.local <<EOF
# Generated by scripts/complete-local-setup.sh — $(date -u +%Y-%m-%d)
NEXT_PUBLIC_APP_URL=http://localhost:3000

DATABASE_URL=postgresql://postgres:aurafit_local_dev@127.0.0.1:54322/postgres

NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY=${NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY}
CLERK_SECRET_KEY=${CLERK_SECRET_KEY}
NEXT_PUBLIC_CLERK_SIGN_IN_URL=/sign-in
NEXT_PUBLIC_CLERK_SIGN_UP_URL=/sign-up
NEXT_PUBLIC_CLERK_AFTER_SIGN_IN_URL=/dashboard
NEXT_PUBLIC_CLERK_AFTER_SIGN_UP_URL=/onboarding

STORAGE_PROVIDER=azure
AZURE_STORAGE_ACCOUNT_NAME=${AZURE_STORAGE_ACCOUNT_NAME}
AZURE_STORAGE_ACCOUNT_KEY=${AZURE_STORAGE_ACCOUNT_KEY}
AZURE_STORAGE_CONNECTION_STRING=${AZURE_STORAGE_CONNECTION_STRING}
AZURE_STORAGE_CONTAINER_WARDROBES=wardrobes
AZURE_STORAGE_CONTAINER_OUTFITS=outfits
AZURE_STORAGE_CONTAINER_PROFILES=profiles

AZURE_OPENAI_ENDPOINT=${AZURE_OPENAI_ENDPOINT}
AZURE_OPENAI_API_KEY=${AZURE_OPENAI_API_KEY}
AZURE_OPENAI_DEPLOYMENT_GPT4O=gpt-4o
AZURE_OPENAI_DEPLOYMENT_EMBED=text-embedding-3-large
AZURE_OPENAI_DEPLOYMENT_IMAGE=dall-e-3
AZURE_OPENAI_API_VERSION=2024-10-01-preview
AI_PROVIDERS=azure,openai
AI_PROVIDER=azure
IMAGE_PROVIDERS=azure,openai,noop

PRODUCT_DISCOVERY_LAYERS=cache,index,shopping,crawl,demo
PRODUCT_SEARCH_CACHE_TTL_SECONDS=21600
PRODUCT_RANKING_ENABLED=true
PRODUCT_CRAWL_MIN_RESULTS=4
PRODUCT_CANDIDATE_POOL_TARGET=20
BOARD_MAX_PER_RETAILER=3
PRODUCT_INDEX_MIN_SCORE=0.55
PRODUCT_CRAWLER_URL=http://localhost:8100
CRAWLER_API_KEY=dev-crawler-key
CRAWL_PAGE_CACHE_TTL_SECONDS=604800

QUEUE_PROVIDERS=inline
CACHE_PROVIDER=memory
GENERATION_PREVIEW_ONLY=true
AFFILIATE_PROVIDERS=amazon,generic
TRYON_PROVIDERS=replicate,noop
CORS_ALLOWED_ORIGINS=http://localhost:3000,http://localhost:8081,exp://${LAN_IP}:8081
EOF

mkdir -p apps/mobile
cat > apps/mobile/.env <<EOF
EXPO_PUBLIC_API_URL=http://${LAN_IP}:3000
EXPO_PUBLIC_CLERK_PUBLISHABLE_KEY=${NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY}
EOF

echo ""
echo "Wrote .env.local and apps/mobile/.env"
echo ""
echo "Next steps:"
echo "  1. Start Docker Desktop"
echo "  2. npm run setup:local     # postgres + db push"
echo "  3. npm run setup:crawler   # product crawler (separate terminal)"
echo "  4. npm run dev"
echo ""
echo "Verify: ./scripts/check-setup.sh"
